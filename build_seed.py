"""
Orchestrator: pulls BTC/ETH derivative data from public APIs -> computes levels ->
generates CryptoLevels_auto.pine (paste once into the TradingView Pine editor).

Crypto clone of gamma-seed/build_seed.py, same operating model:
  1x daily:  python build_seed.py   -> paste the generated Pine -> FREEZE.
  Structure map 7-45 DTE (stable daily lines) vs near map 0-5 DTE (daily weather),
  identical split to the index pipeline.

Data (all public, no keys):
  Deribit  - option board (OI + mark IV) -> GEX flip/walls/max pain/EM + vanna/charm
  Binance  - funding (real prints), OI + 24h delta, long/short ratios -> label text
  OKX      - recent liquidation prints -> clustered context levels (PAST events,
             not a forward heatmap - Coinglass-style forward maps are estimates
             everywhere; we only draw what actually happened)

Fail-soft: every provider block degrades to zeros / yesterday's stored levels
instead of killing the build. Each day = one row per coin in data/levels_*.csv
(idempotent: today's date is replaced on re-run).
"""
