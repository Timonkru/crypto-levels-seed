def gen_auto_pine(levels, today, note=""):
    lines = []
    for coin, _, _ in COINS:
        v = {f: 0.0 for f in FIELDS}
        v.update(levels.get(coin, {}))
        for f in FIELDS:
            lines.append(f"{coin}_{f} = {v[f]:.4f}")
    lines.append(f'LEV_DATE = "{today}{note}"')
    lines.append(f"LEV_Y = {today.year}")
    lines.append(f"LEV_M = {today.month}")
    lines.append(f"LEV_D = {today.day}")
    pine = AUTO_TEMPLATE.replace("__LEVELS__", "\n".join(lines)).replace(
        "__DATE__", str(today))
    out = ROOT / "CryptoLevels_auto.pine"
    out.write_text(pine, encoding="ascii")
    return out


# ------------------------------------------------------------- persistence ----
def store_levels(coin, today, vals):
    """One row per day per coin, idempotent (today's row is replaced)."""
    f = DATA / f"levels_{coin}.csv"
    row = {"date": str(today), **vals}
    if f.exists():
        df = pd.read_csv(f)
        df = df[df["date"] != str(today)]
        df = pd.concat([df, pd.DataFrame([row])], ignore_index=True)
    else:
        df = pd.DataFrame([row])
    df.to_csv(f, index=False)


def load_stored(coin):
    f = DATA / f"levels_{coin}.csv"
    if not f.exists():
        return None
    df = pd.read_csv(f)
    if df.empty:
        return None
    last = df.iloc[-1].to_dict()
    last.pop("date", None)
    return {k: float(v) for k, v in last.items()}


# --------------------------------------------------------------------- main ----
def main():
    today = date.today()
    print(f"=== Crypto-Levels-Seed build  {today} ===\n")
    levels, summary, stale_coins = {}, [], []
    for coin, perp, uly in COINS:
        # -- options: the core (fail here => fall back to stored levels) --
        try:
            ch = P.deribit_chain(coin)
            df = ch.df
            struct_df = df[(df["dte"] >= STRUCT_MIN_DTE) & (df["dte"] <= STRUCT_MAX_DTE)]
            med_iv = float(struct_df["iv"].median()) if len(struct_df) else 0.0
            if med_iv < 0.10:
                raise RuntimeError(f"degenerate chain (median IV {med_iv:.3f} < 0.10)")
            struct = gex.compute_levels(struct_df, ch.spot)
            near = gex.compute_levels(df[df["dte"] <= NEAR_MAX_DTE], ch.spot)
            if struct is None:
                raise RuntimeError("no structure chain")
        except Exception as e:  # noqa: BLE001
            stored = load_stored(coin)
            if stored:
                print(f"[skip] {coin}: {e} -> keeping stored levels")
                levels[coin] = stored
                stale_coins.append(coin)
            else:
                print(f"[skip] {coin}: {e} (no stored levels either)")
            continue

        vals = {"FLIP": g(struct, "gamma_flip"), "CW": g(struct, "call_wall"),
                "PW": g(struct, "put_wall"), "CW2": g(struct, "call_wall2"),
                "PW2": g(struct, "put_wall2"), "NCW": g(near, "call_wall"),
                "NPW": g(near, "put_wall"), "NF": g(near, "gamma_flip"),
                "MP": g(struct, "max_pain"), "SPOT": struct["spot"],
                "EM": g(struct, "exp_move_1d"),
                "GEXBN": struct["total_gex"] / 1e9,
                "VAN": (struct.get("total_vanna") or 0.0) / 1e6,
                "VANK": g(struct, "vanna_strike"),
                "CHM": (struct.get("total_charm") or 0.0) / 1e6,
                "CHMK": g(struct, "charm_strike")}

        # -- derivatives snapshot (fail-soft: zeros hide the label line) --
        try:
            b = P.binance_snapshot(perp)
            vals.update({"FUND": b["funding_8h_pct"], "OIU": b["oi_usd_bn"],
                         "OID": b["oi_d24_pct"], "LSR": b["global_ls"],
                         "TLS": b["top_ls"]})
        except Exception as e:  # noqa: BLE001
            print(f"[warn] {coin}: Binance snapshot failed ({e})")
            vals.update({"FUND": 0.0, "OIU": 0.0, "OID": 0.0, "LSR": 0.0, "TLS": 0.0})

        # -- liquidation clusters (fail-soft: zero levels are not drawn) --
        try:
            lq = P.okx_liq_clusters(uly, spot=struct["spot"])
        except Exception as e:  # noqa: BLE001
            print(f"[warn] {coin}: OKX liquidations failed ({e})")
            lq = []
        for i in range(3):
            vals[f"LQ{i + 1}"] = lq[i]["price"] if i < len(lq) else 0.0
            vals[f"LQ{i + 1}D"] = float(lq[i]["dir"]) if i < len(lq) else 0.0

        levels[coin] = vals
        store_levels(coin, today, vals)
        summary.append(
            f"{coin:4s} spot {vals['SPOT']:.0f} | {struct['regime'].upper():7s} "
            f"| Flip {vals['FLIP']:.0f} ({struct['dist_to_flip_pct'] or 0:+.2f}%) "
            f"| CW {vals['CW']:.0f}/{vals['CW2']:.0f} | PW {vals['PW']:.0f}/{vals['PW2']:.0f} "
            f"| EM1d +/-{vals['EM']:.0f} | GEX {vals['GEXBN']:+.2f}bn "
            f"| ATM-IV {struct['atm_iv'] or 0:.0%}")

    if not levels:
        print("\nNOTHING built - all providers failed. Old Pine stays valid.")
        return 1
    note = f" ({'/'.join(stale_coins)}=stored)" if stale_coins else ""
    out = gen_auto_pine(levels, today, note)
    txt = "\n".join(summary)
    print("\n" + txt)
    (ROOT / "today_levels.txt").write_text(
        f"Crypto levels {today}{note}\n{txt}\n", encoding="utf-8")
    print(f"\nPine written: {out.name} -> paste into the TradingView Pine editor, save, FREEZE.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
